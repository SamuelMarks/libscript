#!/bin/sh
# ## Overview
# Idempotently synthesizes `WATTCP.CFG` for Watt-32 Crynwr packet-driver networking (`ne2k_isa` / `pcnet`) on MS-DOS when online, skipping setup when `LIBSCRIPT_OFFLINE=1`.
# ## Usage
# . "${LIBSCRIPT_ROOT_DIR}/engine/common/dos32/wattcp_cfg.sh" && libscript_ensure_wattcp_cfg

set -feu
_wc_caller_this="${THIS_FILE-}"; _wc_caller_dir="${SCRIPT_DIR-}"
if [ "${SCRIPT_NAME-}" ]; then
  THIS_FILE="${SCRIPT_NAME}"
elif [ "${BASH_SOURCE-}" ]; then
  THIS_FILE="${BASH_SOURCE}"
elif [ "${ZSH_VERSION-}" ]; then
  # shellcheck disable=SC2296
  THIS_FILE="${(%):-%x}"
else
  THIS_FILE="${0}"
fi
case "${STACK+x}" in
  *':'"${THIS_FILE}"':'*)
    [ "${LIBSCRIPT_DEBUG:-0}" = '1' ] && printf '[STOP]     processing "%s"\n' "${THIS_FILE}" >&2
    [ -n "${_wc_caller_dir:-}" ] && SCRIPT_DIR="$_wc_caller_dir"; [ -n "${_wc_caller_this:-}" ] && THIS_FILE="$_wc_caller_this"
    unset SCRIPT_NAME _wc_caller_this _wc_caller_dir || true
    if (return 0 2>/dev/null); then return; else exit 0; fi ;;
  *) [ "${LIBSCRIPT_DEBUG:-0}" = '1' ] && printf '[CONTINUE] processing "%s"\n' "${THIS_FILE}" >&2 ;;
esac
export STACK="${STACK:-}${THIS_FILE}"':'
SCRIPT_DIR=$(cd -- "$(dirname -- "${THIS_FILE}")" && pwd)
: "${LIBSCRIPT_ROOT_DIR:=$(d="$SCRIPT_DIR"; while [ ! -f "$d/libscript.sh" ]; do n="${d%/*}"; [ -z "$n" ] && n="/"; [ "$d" = "$n" ] && break; d="$n"; done; printf '%s\n' "$d")}"

# ## libscript_ensure_wattcp_cfg
# Generates WATTCP.CFG (DHCP or static IPv4 + packet vector) for MS-DOS online networking if not offline.
libscript_ensure_wattcp_cfg() {
  if [ "${LIBSCRIPT_OFFLINE:-0}" = '1' ]; then
    return 0
  fi
  _wc_home="${LIBSCRIPT_HOME:-${TMPDIR:-/tmp}/LIBSCRIP}"
  _wc_dir="${WATTCP_CFG_DIR:-${_wc_home}/ETC}"
  _wc_file="${WATTCP_CFG_FILE:-${_wc_dir}/WATTCP.CFG}"
  mkdir -p "${_wc_dir}"

  _wc_mode="${LIBSCRIPT_DOS_NET_MODE:-dhcp}"
  _wc_vec="${LIBSCRIPT_DOS_PKT_VEC:-0x60}"
  _wc_dns="${LIBSCRIPT_DOS_NAMESERVER:-10.0.2.3}"
  _wc_mtu="${LIBSCRIPT_DOS_MTU:-1500}"

  if [ "${_wc_mode}" = 'static' ]; then
    _wc_ip="${LIBSCRIPT_DOS_IP:-10.0.2.15}"
    _wc_mask="${LIBSCRIPT_DOS_NETMASK:-255.255.255.0}"
    _wc_gw="${LIBSCRIPT_DOS_GATEWAY:-10.0.2.2}"
    cat <<EOF > "${_wc_file}.TMP"
# Generated by LibScript Watt-32 packet-driver configurator (static mode)
pkt.vector = ${_wc_vec}
my_ip = ${_wc_ip}
netmask = ${_wc_mask}
gateway = ${_wc_gw}
nameserver = ${_wc_dns}
mtu = ${_wc_mtu}
sockdelay = 30
EOF
  else
    cat <<EOF > "${_wc_file}.TMP"
# Generated by LibScript Watt-32 packet-driver configurator (DHCP mode)
pkt.vector = ${_wc_vec}
my_ip = dhcp
nameserver = ${_wc_dns}
mtu = ${_wc_mtu}
dhcp.req_list = 1,3,6,15
sockdelay = 30
EOF
  fi
  mv -f "${_wc_file}.TMP" "${_wc_file}"
  WATTCP_CFG="${_wc_dir}"
  export WATTCP_CFG
  printf '%s\n' "${_wc_file}"
}

STACK="${STACK%"${THIS_FILE}":}"
export STACK
[ -n "${_wc_caller_dir:-}" ] && SCRIPT_DIR="$_wc_caller_dir"
[ -n "${_wc_caller_this:-}" ] && THIS_FILE="$_wc_caller_this"
unset SCRIPT_NAME _wc_caller_this _wc_caller_dir || true

if ! (return 0 2>/dev/null); then
  libscript_ensure_wattcp_cfg "$@"
fi
