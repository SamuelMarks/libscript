#!/bin/sh
# ## Overview
# Deterministic Zephyr Kconfig (.conf) fragment and Devicetree (.overlay) merger.
# Produces merged prj.conf/.config, C header autoconf.h, and merged zephyr.dts.
#
# ## Usage
# ./_lib/kernel/zephyr/merge_zephyr_config.sh <out_dir> [board] [kconfig_csv] [dts_csv]

set -feu

if [ "${SCRIPT_NAME-}" ]; then
  THIS_FILE="${SCRIPT_NAME}"
elif [ "${BASH_SOURCE-}" ]; then
  THIS_FILE="${BASH_SOURCE}"
elif [ "${ZSH_VERSION-}" ]; then
  # shellcheck disable=SC2296
  THIS_FILE="${(%):-%x}"
else
  THIS_FILE="${0}"
fi

case "${STACK+x}" in
  *':'"${THIS_FILE}"':'*)
    printf '[STOP]     processing "%s"\n' "${THIS_FILE}" >&2
    if (return 0 2>/dev/null); then return; else exit 0; fi ;;
  *) printf '[CONTINUE] processing "%s"\n' "${THIS_FILE}" >&2 ;;
esac
export STACK="${STACK:-}${THIS_FILE}"':'
SCRIPT_DIR=$(cd -- "$(dirname -- "${THIS_FILE}")" && pwd)
: "${LIBSCRIPT_ROOT_DIR:=$(d="$SCRIPT_DIR"; while [ ! -f "$d/libscript.sh" ]; do n="${d%/*}"; [ -z "$n" ] && n="/"; [ "$d" = "$n" ] && break; d="$n"; done; printf '%s\n' "$d")}"

OUT_DIR="${1:-}"
BOARD="${2:-${ZEPHYR_BOARD:-${LIBSCRIPT_RTOS_BOARD:-qemu_x86_64}}}"
KCONFIG_CSV="${3:-${ZEPHYR_KCONFIG_FRAGMENTS:-minimal_footprint.conf,picolibc.conf}}"
DTS_CSV="${4:-${ZEPHYR_DTS_OVERLAYS:-}}"

if [ -z "$OUT_DIR" ]; then
  printf '[ERROR] Usage: merge_zephyr_config.sh <out_dir> [board] [kconfig_csv] [dts_csv]\n' >&2
  exit 1
fi
mkdir -p "$OUT_DIR"

CONF_OUT="${OUT_DIR}/.config"
PRJ_OUT="${OUT_DIR}/prj.merged.conf"
HDR_OUT="${OUT_DIR}/autoconf.h"
DTS_OUT="${OUT_DIR}/zephyr.dts"

printf '# Merged by LibScript Zephyr Kconfig Engine for board=%s\n' "$BOARD" > "${CONF_OUT}.tmp"
_old_ifs="$IFS"
IFS=','
for _frag in $KCONFIG_CSV; do
  [ -n "$_frag" ] || continue
  _fpath="$_frag"
  if [ ! -f "$_fpath" ] && [ -f "${SCRIPT_DIR}/configs/${_frag}" ]; then
    _fpath="${SCRIPT_DIR}/configs/${_frag}"
  elif [ ! -f "$_fpath" ] && [ -f "${SCRIPT_DIR}/configs/${_frag}.conf" ]; then
    _fpath="${SCRIPT_DIR}/configs/${_frag}.conf"
  fi
  if [ -f "$_fpath" ]; then
    {
      printf '# --- Fragment: %s ---\n' "$(basename "$_fpath")"
      cat "$_fpath"
      printf '\n'
    } >> "${CONF_OUT}.tmp"
  fi
done
IFS="$_old_ifs"

mv "${CONF_OUT}.tmp" "$CONF_OUT"
cp -f "$CONF_OUT" "$PRJ_OUT"

{
  printf '/* Auto-generated by LibScript merge_zephyr_config.sh */\n'
  printf '#ifndef LIBSCRIPT_ZEPHYR_AUTOCONF_H\n'
  printf '#define LIBSCRIPT_ZEPHYR_AUTOCONF_H\n'
  printf '#define CONFIG_BOARD "%s"\n' "$BOARD"
  awk -F= '
    /^CONFIG_[A-Za-z0-9_]+=/ {
      key = $1
      val = substr($0, index($0, "=") + 1)
      if (val == "y") {
        printf "#ifndef %s\n#define %s 1\n#endif\n", key, key
      } else if (val == "n") {
        printf "#undef %s\n", key
      } else {
        printf "#ifndef %s\n#define %s %s\n#endif\n", key, key, val
      }
    }
  ' "$CONF_OUT"
  printf '#endif\n'
} > "${HDR_OUT}.tmp"
mv "${HDR_OUT}.tmp" "$HDR_OUT"

{
  printf '/dts-v1/;\n'
  printf '/* Synthesized Devicetree for Zephyr board: %s */\n' "$BOARD"
  printf '/ {\n'
  printf '    model = "LibScript Zephyr %s Appliance";\n' "$BOARD"
  printf '    compatible = "zephyr,%s";\n' "$BOARD"
  printf '    chosen {\n'
  printf '        zephyr,console = &uart0;\n'
  printf '        zephyr,sram = &sram0;\n'
  printf '    };\n'
  printf '    uart0: serial@0 { status = "okay"; };\n'
  printf '    sram0: memory@0 { device_type = "memory"; };\n'
  printf '};\n'
} > "${DTS_OUT}.tmp"

if [ -n "$DTS_CSV" ]; then
  _old_ifs="$IFS"
  IFS=','
  for _ov in $DTS_CSV; do
    if [ -n "$_ov" ] && [ -f "$_ov" ]; then
      printf '\n/* --- Overlay: %s --- */\n' "$(basename "$_ov")" >> "${DTS_OUT}.tmp"
      cat "$_ov" >> "${DTS_OUT}.tmp"
    fi
  done
  IFS="$_old_ifs"
fi
mv "${DTS_OUT}.tmp" "$DTS_OUT"
exit 0
