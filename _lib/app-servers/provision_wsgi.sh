#!/bin/sh
# ## Overview
# Declarative Backend Orchestrator. Provisions Python venvs, templates configs,
# runs migrations, and registers N-tier services (Gunicorn/Celery) via systemd.
#
# ## Usage
#   ./provision_wsgi.sh --app-dir <dir> --manifest <path> --packaging <path>

set -feu

if [ "${SCRIPT_NAME-}" ]; then
  THIS_FILE="${SCRIPT_NAME}"
elif [ "${BASH_SOURCE-}" ]; then
  THIS_FILE="${BASH_SOURCE}"
elif [ "${ZSH_VERSION-}" ]; then
  # shellcheck disable=SC2296
  THIS_FILE="${(%):-%x}"
else
  THIS_FILE="${0}"
fi
case "${STACK+x}" in
  *':'"${THIS_FILE}"':'*)
    printf '[STOP]     processing "%s"\n' "${THIS_FILE}" >&2
    if (return 0 2>/dev/null); then return; else exit 0; fi ;;
  *) printf '[CONTINUE] processing "%s"\n' "${THIS_FILE}" >&2 ;;
esac
export STACK="${STACK:-}${THIS_FILE}"':'
SCRIPT_DIR=$(cd -- "$(dirname -- "${THIS_FILE}")" && pwd)
: "${LIBSCRIPT_ROOT_DIR:=$(d="$SCRIPT_DIR"; while [ ! -f "$d/libscript.sh" ]; do n="${d%/*}"; [ -z "$n" ] && n="/"; [ "$d" = "$n" ] && break; d="$n"; done; printf '%s\n' "$d")}"
export DIR="${SCRIPT_DIR}"

app_dir=""
manifest_path=""
packaging_path=""

while [ $# -gt 0 ]; do
  case "$1" in
    --app-dir) app_dir="$2"; shift 2 ;;
    --manifest) manifest_path="$2"; shift 2 ;;
    --packaging) packaging_path="$2"; shift 2 ;;
    *) shift ;;
  esac
done

if [ -z "$app_dir" ] || [ -z "$manifest_path" ] || [ -z "$packaging_path" ]; then
  printf 'Error: --app-dir, --manifest, and --packaging are required.\n' >&2
  exit 1
fi

venv_dir="$app_dir/venv"
data_dir="$app_dir/data"
logs_dir="$app_dir/logs"

# 1. Persistent Storage Mapping
mkdir -p "$data_dir" "$logs_dir"
chmod 700 "$data_dir" "$logs_dir"

# 2. Automated Python venv scaffolding
if [ ! -d "$venv_dir" ]; then
  # Assume python is available in PATH or via libscript environment
  python3 -m venv "$venv_dir"
fi

# 3. Application Configuration Rendering (Mock generation for shell)
# In reality, this would parse vars.schema.json using jq and write out .env/yaml.
env_file="$app_dir/.env"
if [ ! -f "$env_file" ]; then
    printf '# Auto-generated by provision_wsgi.sh\nDATA_DIR="%s"\nLOGS_DIR="%s"\n' "$data_dir" "$logs_dir" > "$env_file"
fi

# 4. Plugin & Extension Pipeline
req_file="$app_dir/requirements.txt"
if [ -f "$req_file" ]; then
  # Idempotently install deps/XBlocks
  "$venv_dir/bin/pip" install -q -r "$req_file"
fi

# 5. Multi-daemon processing & Cross-Init Service Registration
# This extracts services from packaging.json and registers them via libscript_install_service.
if [ -f "${LIBSCRIPT_ROOT_DIR}/_lib/_common/service.sh" ]; then
  SCRIPT_NAME="${LIBSCRIPT_ROOT_DIR}/_lib/_common/service.sh"
  export SCRIPT_NAME
  # shellcheck disable=SC1090
  . "${SCRIPT_NAME}"
  unset SCRIPT_NAME || true
fi

if command -v jq >/dev/null 2>&1; then
  jq -c '.services[]?' "$packaging_path" | while read -r svc; do
    svc_id=$(printf '%s' "$svc" | jq -r '.id')
    svc_type=$(printf '%s' "$svc" | jq -r '.type')
    case "$svc_type" in
      wsgi|asgi)
        port=$(printf '%s' "$svc" | jq -r '.port_binding')
        entrypoint=$(printf '%s' "$svc" | jq -r '.wsgi_entrypoint')
        libscript_install_service "$svc_id" "$venv_dir/bin/gunicorn -b 127.0.0.1:$port $entrypoint" "$app_dir" "$svc_id" "" "" "$env_file"
        libscript_service enable "$svc_id" || true
        libscript_service start "$svc_id" || true
        ;;
      worker|beat)
        worker_class=$(printf '%s' "$svc" | jq -r '.worker_class')
        libscript_install_service "$svc_id" "$venv_dir/bin/celery -A $worker_class worker" "$app_dir" "$svc_id worker" "" "" "$env_file"
        libscript_service enable "$svc_id" || true
        libscript_service start "$svc_id" || true
        ;;
    esac
  done
fi

# 6. Idempotent Lifecycle Hooks (Migrations, Indexing)
if command -v jq >/dev/null 2>&1; then
  jq -c '.lifecycle_hooks.post_install[]?' "$packaging_path" | while read -r hook; do
    cmd=$(printf '%s' "$hook" | jq -r '.command')
    (cd "$app_dir" && sh -c "$cmd") || true
  done
fi

exit 0
