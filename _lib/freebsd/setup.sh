#!/bin/sh
# ## Overview
# FreeBSD system and kernel compilation and installation engine.
# Orchestrates buildworld/buildkernel or binary base/kernel staging into target sysroot,
# and populates /boot/loader.conf and /etc/rc.conf.
# ## Usage
# Run `setup.sh [--strict | --allow-stub] [action]` (default: compile).

set -feu

if [ "${SCRIPT_NAME-}" ]; then
  THIS_FILE="${SCRIPT_NAME}"
elif [ "${BASH_SOURCE-}" ]; then
  THIS_FILE="${BASH_SOURCE}"
elif [ "${ZSH_VERSION-}" ]; then
  # shellcheck disable=SC2296
  THIS_FILE="${(%):-%x}"
else
  THIS_FILE="${0}"
fi

case "${STACK+x}" in
  *':'"${THIS_FILE}"':'*)
    printf '[STOP]     processing "%s"\n' "${THIS_FILE}" >&2
    if (return 0 2>/dev/null); then return; else exit 0; fi ;;
  *) printf '[CONTINUE] processing "%s"\n' "${THIS_FILE}" >&2 ;;
esac
export STACK="${STACK:-}${THIS_FILE}"':'
SCRIPT_DIR=$(cd -- "$(dirname -- "${THIS_FILE}")" && pwd)
: "${LIBSCRIPT_ROOT_DIR:=$(d="$SCRIPT_DIR"; while [ ! -f "$d/libscript.sh" ]; do n="${d%/*}"; [ -z "$n" ] && n="/"; [ "$d" = "$n" ] && break; d="$n"; done; printf '%s\n' "$d")}"

STRICT_BUILD="${LIBSCRIPT_STRICT_IMAGE_BUILD:-0}"
ALLOW_STUB="${LIBSCRIPT_ALLOW_STUB:-0}"

while [ $# -gt 0 ]; do
  case "$1" in
    --help|-h)
      printf 'Usage: %s [--strict | --allow-stub] [compile|install|clean]\n' "$(basename "$THIS_FILE")"
      exit 0
      ;;
    --strict)
      STRICT_BUILD=1
      shift
      ;;
    --allow-stub)
      ALLOW_STUB=1
      shift
      ;;
    *)
      break
      ;;
  esac
done

ACTION="${1:-compile}"
TARGET_SYSROOT="${LIBSCRIPT_TARGET_SYSROOT:-${LIBSCRIPT_ROOT_DIR}/build/target-sysroot}"
STAMPS_DIR="${TARGET_SYSROOT}/var/lib/libscript/stamps"
STAMP_FILE="${STAMPS_DIR}/.stamp.freebsd_system"

mkdir -p "$STAMPS_DIR"

if [ "$ACTION" = "clean" ]; then
  rm -f "$STAMP_FILE"
  exit 0
fi

if [ -f "$STAMP_FILE" ] && [ -s "$TARGET_SYSROOT/boot/kernel/kernel" ]; then
  if grep -q '^mode=stub$' "$STAMP_FILE" 2>/dev/null && [ "$STRICT_BUILD" = "1" ]; then
    rm -f "$STAMP_FILE"
  else
    printf '[SKIP]  %s already installed (%s)\n' "freebsd_system" "$STAMP_FILE"
    exit 0
  fi
fi

printf '[RECIPE] Staging %s into %s (action: %s)\n' "FreeBSD System Engine" "$TARGET_SYSROOT" "$ACTION"

mkdir -p "$TARGET_SYSROOT/boot/kernel" "$TARGET_SYSROOT/etc" "$TARGET_SYSROOT/etc/rc.conf.d"

STAMP_MODE='native'
if [ -d "${FREEBSD_SRC_DIR:-/usr/src}" ] && [ -f "${FREEBSD_SRC_DIR:-/usr/src}/Makefile.inc1" ] && [ "${ACTION}" = "compile" ] && [ "${LIBSCRIPT_FREEBSD_BUILDWORLD:-0}" = "1" ]; then
  MAKEOBJDIRPREFIX="${LIBSCRIPT_BUILD_DIR:-${LIBSCRIPT_ROOT_DIR}/build/freebsd-obj}"
  mkdir -p "$MAKEOBJDIRPREFIX"
  export MAKEOBJDIRPREFIX
  if [ "$(uname -s 2>/dev/null || printf '')" != "FreeBSD" ] && [ -x "${FREEBSD_SRC_DIR:-/usr/src}/tools/build/make.py" ]; then
    "${FREEBSD_SRC_DIR:-/usr/src}/tools/build/make.py" TARGET=amd64 TARGET_ARCH=amd64 buildworld buildkernel
    "${FREEBSD_SRC_DIR:-/usr/src}/tools/build/make.py" TARGET=amd64 TARGET_ARCH=amd64 installworld installkernel DESTDIR="$TARGET_SYSROOT"
  else
    make -C "${FREEBSD_SRC_DIR:-/usr/src}" buildworld buildkernel
    make -C "${FREEBSD_SRC_DIR:-/usr/src}" installworld installkernel DESTDIR="$TARGET_SYSROOT"
  fi
elif [ -x "${SCRIPT_DIR}/distro/base.sh" ] && [ "${LIBSCRIPT_OFFLINE:-0}" = "0" ] && [ "${LIBSCRIPT_FETCH_FREEBSD_BASE:-0}" = "1" ]; then
  STACK="" "${SCRIPT_DIR}/distro/base.sh" "$TARGET_SYSROOT" "${FREEBSD_VERSION:-14.1-RELEASE}" "${LIBSCRIPT_TARGET_ARCH:-amd64}"
fi

if [ ! -f "$TARGET_SYSROOT/boot/loader.conf" ]; then
  cat <<'LOADER_EOF' > "$TARGET_SYSROOT/boot/loader.conf"
# /boot/loader.conf generated by LibScript
autoboot_delay="2"
zfs_load="YES"
vfs.root.mountfrom="zfs:zroot/ROOT/default"
LOADER_EOF
fi

if [ ! -f "$TARGET_SYSROOT/etc/rc.conf" ]; then
  cat <<'RCCONF_EOF' > "$TARGET_SYSROOT/etc/rc.conf"
# /etc/rc.conf generated by LibScript
hostname="libscript-freebsd"
zfs_enable="YES"
sshd_enable="YES"
sendmail_enable="NONE"
ifconfig_DEFAULT="DHCP"
RCCONF_EOF
fi

if [ ! -s "$TARGET_SYSROOT/boot/kernel/kernel" ] || grep -q '^FreeBSD Kernel Image$' "$TARGET_SYSROOT/boot/kernel/kernel" 2>/dev/null; then
  if [ "$STRICT_BUILD" = "1" ] && [ "$ALLOW_STUB" != "1" ]; then
    printf '[ERROR] Strict FreeBSD kernel staging failed: set LIBSCRIPT_FETCH_FREEBSD_BASE=1 or provide FREEBSD_SRC_DIR.\n' >&2
    rm -f "$STAMP_FILE"
    exit 1
  fi
  STAMP_MODE='stub'
  printf 'FreeBSD Kernel Image\n' > "$TARGET_SYSROOT/boot/kernel/kernel"
fi

printf 'mode=%s\ntimestamp=%s\n' "$STAMP_MODE" "$(date -u +"%Y-%m-%dT%H:%M:%SZ")" > "${STAMP_FILE}.tmp"
mv "${STAMP_FILE}.tmp" "$STAMP_FILE"
printf '[OK]    %s staged successfully (mode=%s): %s\n' "freebsd_system" "$STAMP_MODE" "$STAMP_FILE"
exit 0
