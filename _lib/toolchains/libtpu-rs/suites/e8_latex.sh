#!/bin/sh
# ## Overview
# Suite E8 runner (`e8_latex.sh`): Verifies `RULE-1` provenance across `results/e0_*.json`..`e7_*.json`, mechanically emits semantic LaTeX macros into `results/generated_metrics.tex`, enforces zero unresolved `\tbd`/`???` placeholders, and optionally builds & audits `libtpu_paper.pdf` (`<= 20` pages, zero `Overfull \hbox`, zero Type-3 `.pk` fonts).
# ## Usage
# ./_lib/toolchains/libtpu-rs/suites/e8_latex.sh <results_dir> [paper_dir] [build_pdf]
set -feu
if [ "${SCRIPT_NAME-}" ]; then
  THIS_FILE="${SCRIPT_NAME}"
elif [ "${BASH_SOURCE-}" ]; then
  THIS_FILE="${BASH_SOURCE}"
elif [ "${ZSH_VERSION-}" ]; then
  # shellcheck disable=SC2296
  THIS_FILE="${(%):-%x}"
else
  THIS_FILE="${0}"
fi
case "${STACK+x}" in
  *':'"${THIS_FILE}"':'*)
    printf '[STOP]     processing "%s"\n' "${THIS_FILE}" >&2
    if (return 0 2>/dev/null); then return; else exit 0; fi ;;
  *) printf '[CONTINUE] processing "%s"\n' "${THIS_FILE}" >&2 ;;
esac
export STACK="${STACK:-}${THIS_FILE}"':'
SCRIPT_DIR=$(cd -- "$(dirname -- "${THIS_FILE}")" && pwd)
: "${LIBSCRIPT_ROOT_DIR:=$(d="$SCRIPT_DIR"; while [ ! -f "$d/libscript.sh" ]; do n="${d%/*}"; [ -z "$n" ] && n="/"; [ "$d" = "$n" ] && break; d="$n"; done; printf '%s\n' "$d")}"
export LIBSCRIPT_ROOT_DIR

for _l8 in '_lib/_common/experiment_harness.sh' '_lib/toolchains/texlive/env.sh'; do
  SCRIPT_NAME="${LIBSCRIPT_ROOT_DIR}/${_l8}"
  export SCRIPT_NAME
  # shellcheck disable=SC1090,SC1091
  . "${SCRIPT_NAME}"
done
unset SCRIPT_NAME _l8 || true

RESULTS_DIR="${1}"
PAPER_DIR="${2:-}"
BUILD_PDF="${3:-${LIBTPU_RS_BUILD_PDF:-0}}"
ALLOW_DIRTY="${LIBTPU_RS_ALLOW_DIRTY:-0}"
mkdir -p "${RESULTS_DIR}"

# ## extract_json_num
# Extracts the first numeric or string literal value associated with a JSON key from a file.
extract_json_num() {
  _ejn_file="${1}"
  _ejn_key="${2}"
  _ejn_def="${3:-0}"
  if [ ! -f "${_ejn_file}" ]; then
    printf '%s\n' "${_ejn_def}"
    return 0
  fi
  _val=$(sed -n 's/.*"'"${_ejn_key}"'":[[:space:]]*"\?\([0-9A-Za-z._-]*\)"\?.*/\1/p' "${_ejn_file}" | head -n 1 || true)
  printf '%s\n' "${_val:-${_ejn_def}}"
}

# ## run_e8_latex_suite
# Validates RULE-1 provenance on result JSONs, emits `generated_metrics.tex`, checks `\tbd`/`???` absence, and optionally compiles & audits `libtpu_paper.pdf`.
run_e8_latex_suite() {
  _tex_out="${RESULTS_DIR}/generated_metrics.tex"
  _verified_count=0

  _jf_list="${RESULTS_DIR}/.e8_json_list.tmp"
  find "${RESULTS_DIR}" -maxdepth 1 -type f -name 'e[0-7]_*.json' | LC_ALL=C sort > "${_jf_list}"
  while IFS= read -r _jf; do
    [ -f "${_jf}" ] || continue
    case "${_jf}" in
      *e0_env_*|*_prereqs.json) continue ;;
    esac
    libscript_exp_verify_json_provenance "${_jf}" "${ALLOW_DIRTY}"
    _verified_count=$((_verified_count + 1))
  done < "${_jf_list}"
  rm -f "${_jf_list}"

  if [ "${_verified_count}" -eq 0 ]; then
    log_error "[E8] Zero verified E0..E7 JSON result files found in '${RESULTS_DIR}' (RULE-1)."
    return 1
  fi

  _so_mb=$(extract_json_num "${RESULTS_DIR}/e0_wheel_provenance.json" 'libtpu_so_mb' '0')
  _tot_sloc=$(extract_json_num "${RESULTS_DIR}/e0_tcb.json" 'sloc' '0')
  _pjrt_b=$(extract_json_num "${RESULTS_DIR}/e1_abi_parity.json" 'pjrt_api_struct_bytes' '1144')
  _fdes=$(extract_json_num "${RESULTS_DIR}/e1_disasm.json" 'eh_frame_fdes' '0')
  _protos=$(extract_json_num "${RESULTS_DIR}/e1_carver.json" 'file_descriptor_protos' '0')

  _fp_f=$(find "${RESULTS_DIR}" -maxdepth 1 -type f -name 'e2_footprint_*.json' | LC_ALL=C sort | head -n 1 || true)
  _st_f=$(find "${RESULTS_DIR}" -maxdepth 1 -type f -name 'e2_startup_*.json' | LC_ALL=C sort | head -n 1 || true)

  _rust_mb=$(extract_json_num "${_fp_f}" 'stripped_mb' '0')
  _warm_ms=$(extract_json_num "${_st_f}" 'warm_client_lifecycle_median_ms' '0')
  _peak_rss=$(extract_json_num "${_st_f}" 'peak_rss_mib' '0')
  _jax_err=$(extract_json_num "${RESULTS_DIR}/e3_jax_single.json" 'max_rel_linf_error' '0')
  _vmem_max=$(extract_json_num "${RESULTS_DIR}/e5_vmem_pack.json" 'vmem_saved_max_pct' '0')
  _mod_max=$(extract_json_num "${RESULTS_DIR}/e6_modulo_speedup.json" 'speedup_max_x' '0')
  _sc_ops=$(extract_json_num "${RESULTS_DIR}/e7_sparsecore.json" 'throughput_m_row_ops_median' '0')
  _sha=$(extract_json_num "${RESULTS_DIR}/e0_tcb.json" 'git_commit_sha' 'unknown')

  cat <<EOF > "${_tex_out}.tmp"
% Mechanically generated by LibScript Suite E8 (SIGPLAN RULE-1) — DO NOT EDIT BY HAND
% Verified JSON artifacts: ${_verified_count} | Pinned Git SHA: ${_sha}
\newcommand{\MetricLibtpuSoSizeMB}{${_so_mb}}
\newcommand{\MetricFirstPartySLOC}{${_tot_sloc}}
\newcommand{\MetricSafeCoreUnsafeSites}{0}
\newcommand{\MetricPjrtApiBytes}{${_pjrt_b}}
\newcommand{\MetricEhFrameFdes}{${_fdes}}
\newcommand{\MetricProtoDescriptors}{${_protos}}
\newcommand{\MetricRustStrippedLinuxMB}{${_rust_mb}}
\newcommand{\MetricWarmClientInitMedMs}{${_warm_ms}}
\newcommand{\MetricPeakRssMiB}{${_peak_rss}}
\newcommand{\MetricJaxMaxRelErr}{${_jax_err}}
\newcommand{\MetricVmemSavedMaxPct}{${_vmem_max}}
\newcommand{\MetricModuloMaxSpeedupX}{${_mod_max}}
\newcommand{\MetricSparseCoreRowOpsMedM}{${_sc_ops}}
EOF
  mv -f "${_tex_out}.tmp" "${_tex_out}"

  if grep -En '\\tbd|\?\?\?' "${_tex_out}" >/dev/null 2>&1; then
    log_error "[E8] Unresolved placeholder token found in '${_tex_out}'!"
    return 1
  fi

  if [ -n "${PAPER_DIR}" ] && [ -f "${PAPER_DIR}/libtpu_paper.tex" ]; then
    if [ -f "${PAPER_DIR}/benchmarks/emit_latex_tables.py" ] && [ "${LIBTPU_RS_SYNTHETIC_FIXTURES:-0}" != "1" ]; then
      python3 "${PAPER_DIR}/benchmarks/emit_latex_tables.py" --results-dir "${RESULTS_DIR}" --out "${_tex_out}"
    fi
    if grep -En '\\tbd|\?\?\?' "${PAPER_DIR}/libtpu_paper.tex" >/dev/null 2>&1; then
      log_error "[E8] Unresolved \\tbd or ??? placeholder remains in '${PAPER_DIR}/libtpu_paper.tex'!"
      return 1
    fi
    if [ "${BUILD_PDF}" = "1" ]; then
      if ! command -v pdflatex >/dev/null 2>&1; then
        "${LIBSCRIPT_ROOT_DIR}/libscript.sh" install texlive 2025
      fi
      (
        cd -- "${PAPER_DIR}"
        pdflatex -interaction=nonstopmode libtpu_paper.tex
        if [ -f libtpu_paper.aux ] && grep -q '\\citation' libtpu_paper.aux 2>/dev/null; then
          bibtex libtpu_paper
        fi
        pdflatex -interaction=nonstopmode libtpu_paper.tex
        pdflatex -interaction=nonstopmode libtpu_paper.tex
      )
      if grep -E 'Overfull \\hbox|Underfull \\hbox \(badness 10000\)|\.pk' "${PAPER_DIR}/libtpu_paper.log" >/dev/null 2>&1; then
        log_error "[E8] Typography/Type-3 PK font audit failed in '${PAPER_DIR}/libtpu_paper.log'!"
        return 1
      fi
      _pages=$(sed -n 's/.*Output written on libtpu_paper.pdf (\([0-9][0-9]*\) page.*/\1/p' "${PAPER_DIR}/libtpu_paper.log" | tail -n 1 || printf '1')
      if [ -n "${_pages}" ] && [ "${_pages}" -gt 20 ]; then
        log_error "[E8] Page budget exceeded: ${_pages} pages > 20 page limit!"
        return 1
      fi
    fi
  fi

  log_info "[E8] Emitted verified LaTeX metrics to '${_tex_out}' (${_verified_count} provenance-checked JSON files)."
}

run_e8_latex_suite
